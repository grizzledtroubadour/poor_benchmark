#!/usr/bin/env python3
"""Aggregate the full SSP table (ssp_full_data.csv).

Reconstruct a historical missing step: 08_create_ssp_datasets.py consumes
output/ssp_full_data.csv, originally generated by a lost script. Rebuild it from current outputs:

1. Rows and aa_seq/file_type come from output/stage4_cluster_representatives.csv
            (40,067 representative chains; full chain sequence and source structure format).
2. Labels come from output/dssp_labels.csv ss8: authoritative DSSP states per resolved residue,
            mapped as H0 G1 I2 E3 B4 T5 S6 P7 C8.
3. aa_seq may exceed DSSP sequence length because DSSP drops incomplete-backbone residues.
            Map identical sequences directly; otherwise align with difflib.SequenceMatcher (autojunk=True).
            Map equal blocks directly and replace blocks positionally; uncovered residues receive -1
            (ignore index). This reproduces all 40,067 historical rows.

Output: output/ssp_full_data.csv; columns unique_id, aa_seq, file_type, labels.
Labels are space-separated strings such as [8 8 3 ...], with length == len(aa_seq).

Known historical deviation: 787 existing file_type values say pdb despite source files being
.cif.gz only (see stage2_chain_metadata.csv). Step 08 does not consume this field.
This script emits correct representative metadata values; DATA_PROCESS.md records the difference.

Usage:
    python scripts/07_aggregate_ssp_full_data.py                    # Write to output/.
    python scripts/07_aggregate_ssp_full_data.py --out output/_verify_ssp/ssp_full_data.csv
"""
import argparse
import difflib
from pathlib import Path

import pandas as pd

TASK_DIR = Path(__file__).resolve().parent.parent
OUTPUT_DIR = TASK_DIR / "output"

DSSP_LABELS = OUTPUT_DIR / "dssp_labels.csv"
REPRESENTATIVES = OUTPUT_DIR / "stage4_cluster_representatives.csv"

SS8_TO_INT = {"H": 0, "G": 1, "I": 2, "E": 3, "B": 4, "T": 5, "S": 6, "P": 7,
              "C": 8, " ": 8}


def build_labels(aa_seq: str, dssp_seq: str, ss8: str) -> list:
    """Map DSSP ss8 onto full aa_seq, using -1 for residues missing from DSSP."""
    if aa_seq == dssp_seq:
        return [SS8_TO_INT[c] for c in ss8]
    lab = [-1] * len(aa_seq)
    sm = difflib.SequenceMatcher(None, aa_seq, dssp_seq)  # autojunk=True (default)
    for tag, a0, a1, d0, d1 in sm.get_opcodes():
        if tag == "equal":
            for k in range(a1 - a0):
                lab[a0 + k] = SS8_TO_INT[ss8[d0 + k]]
        elif tag == "replace":
            for k in range(min(a1 - a0, d1 - d0)):
                lab[a0 + k] = SS8_TO_INT[ss8[d0 + k]]
        # delete: retain -1; insert: ignore extra DSSP residues.
    return lab


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path,
                    default=OUTPUT_DIR / "ssp_full_data.csv",
                    help="Output path (default output/ssp_full_data.csv)")
    args = ap.parse_args()

    dssp = pd.read_csv(DSSP_LABELS)
    rep = pd.read_csv(REPRESENTATIVES)
    # Match historical row order: dssp_labels.csv sorted by chain_key.
    df = dssp[["chain_key", "seq", "ss8"]].merge(
        rep[["chain_key", "seq", "file_type"]],
        on="chain_key", suffixes=("_dssp", ""),
    )
    assert len(df) == len(rep) == len(dssp)

    n_aligned = 0
    rows = []
    for r in df.itertuples():
        lab = build_labels(r.seq, r.seq_dssp, r.ss8)
        assert len(lab) == len(r.seq)
        n_aligned += r.seq != r.seq_dssp
        rows.append({
            "unique_id": r.chain_key,
            "aa_seq": r.seq,
            "file_type": r.file_type,
            "labels": "[" + " ".join(map(str, lab)) + "]",
        })
    print(f"chains: {len(rows)}, aligned via SequenceMatcher: {n_aligned}")

    out = pd.DataFrame(rows, columns=["unique_id", "aa_seq", "file_type", "labels"])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(args.out, index=False)
    print(f"saved: {args.out} ({len(out)} rows)")


if __name__ == "__main__":
    main()
